const DEFAULT_ICONS: IconKey[] = ['zielgruppe', 'motive', 'auswertung']

export function OnlineKampagnen({
  ueberschrift = 'ONLINE-KAMPAGNEN',
  untertitel,
  items,
}: OnlineKampagnenProps) {
  const list =
    items?.filter((i) => i?.titel).map((item, i) => ({
      ...item,
      icon: item.icon || DEFAULT_ICONS[i] || 'zielgruppe',
    })) ?? []

  if (!list.length) return null

  return (
    <section className="bg-white py-20 md:py-32">
      <div className="mx-auto flex w-full max-w-[1780px] flex-col items-center px-5 sm:px-8">
        <div className="w-full max-w-[1716px] text-center">
          <h2 className="heading-section text-brand-black md:text-[56px] md:leading-none md:tracking-[-0.56px]">
            {ueberschrift}
          </h2>
          {untertitel ? (
            <p className="mx-auto mt-4 max-w-[900px] font-poppins text-sm font-normal leading-[1.5] text-brand-black sm:text-base md:mt-6">
              {untertitel}
            </p>
          ) : null}
        </div>

        <div className="mt-10 grid w-full grid-cols-1 gap-8 sm:grid-cols-2 lg:grid-cols-3">
          {list.map((item) => (
            <article
              key={item.titel}
              className="@container flex min-w-0 flex-col justify-between gap-10 rounded-[24px] bg-brand-black p-10 lg:h-[979px]"
            >
              <CardGraphic name={item.icon as IconKey} />
              <div className="flex min-w-0 flex-col gap-2">
                <h3 className="font-unbounded text-[clamp(1.05rem,7cqi,1.75rem)] font-extrabold leading-[1.1] tracking-normal text-brand-yellow [text-transform:none]">
                  {item.titel}
                </h3>
                {item.text ? (
                  <p className="font-poppins text-[clamp(0.8125rem,4.2cqi,1rem)] font-normal leading-[1.5] text-[#B8B8B8]">
                    {item.text}
                  </p>
                ) : null}
              </div>
            </article>
          ))}
        </div>
      </div>
    </section>
  )
}
